    [Theory]
    [MemberData(nameof(SweptSlopeAngles))]
    public void Grade_AtAnySlopeAngle_NeverReturnsTopologyWorseThanInput(double angle)
    {
        var (result, message, inputFaceCount, inputFaces) = Grade(angle);

        if (result == null)
        {
            // A refusal is an acceptable outcome, but it must be an explained one: a null result with
            // no message reads downstream as "nothing to do" rather than "this failed".
            Assert.False(string.IsNullOrWhiteSpace(message), $"{angle} deg failed without a message.");
            return;
        }

        var input = MeshTopologyValidator.AnalyzeBoundaryGraph(inputFaces, inputFaceCount);
        var output = MeshTopologyValidator.AnalyzeBoundaryGraph(result.Faces, result.FaceCount);

        Assert.True(
            output.BoundaryComponentCount <= input.BoundaryComponentCount,
            $"{angle} deg reported success while raising boundary loops from " +
            $"{input.BoundaryComponentCount} to {output.BoundaryComponentCount}.");
        Assert.True(
            output.NonManifoldEdgeCount <= input.NonManifoldEdgeCount,
            $"{angle} deg reported success while raising non-manifold edges from " +
            $"{input.NonManifoldEdgeCount} to {output.NonManifoldEdgeCount}.");
        Assert.True(
            !output.HasOpenBoundaryChains || input.HasOpenBoundaryChains,
            $"{angle} deg reported success while opening naked-edge chains.");
    }

