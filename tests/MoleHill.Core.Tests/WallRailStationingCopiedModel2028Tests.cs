    [MemberData(nameof(RailPairs))]
    public void Synchronize_JoinedModelWall_PreservesRailsWithoutFoldedCells(int firstId, int secondId, double[] a, double[] b)
    {
        var result = WallRailStationing.Synchronize(a, b, false, .005);
        Assert.True(result.First.Length == result.Second.Length, $"Unequal station counts for model rails {firstId}/{secondId}.");
        WallRailStationingTests.AssertStripDoesNotFold(result.First, result.Second);
        WallRailStationingTests.AssertVerticesRetained(a, result.First);
        WallRailStationingTests.AssertVerticesRetained(b, result.Second);
    }

