/// <summary>
/// A window takes each face its pads reach whole, so its faces stick out past the reach box; the locks and
/// breaklines it hands the grader must be chosen by the faces, not by that box. Here (a coarse contour TIN
/// copied from a Balance Pad report) the 47.86 m contour lies on the window's faces just beyond the second
/// pad's reach box. Chosen by the box, the lock was dropped and the windowed batter cut straight through the
/// contour: 953 m3 more cut than the whole-mesh grade, which the card then built.
/// </summary>
