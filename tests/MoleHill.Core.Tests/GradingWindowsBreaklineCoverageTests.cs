    [Fact]
    public void GradeWindowed_LockOnWindowFaceBeyondReachBox_MatchesWholeMeshGrade()
    {
        (PadGradeRequest request, PadGrader.LockCurve[] locks) = Scene();

        GradingResult whole = PadGrader.Grade(request).Result!;
        GradingResult windowed = PadGrader.GradeWindowed(request, previous: null, new GradingWindows.Memo(), new List<string>()).Result!;

        Assert.Equal(whole.CutVolume, windowed.CutVolume, 1);
        Assert.Equal(whole.FillVolume, windowed.FillVolume, 1);

        // The case only tests anything while that contour stops the batter.
        var withoutContour = new PadGradeRequest
        {
            Terrain = request.Terrain,
            Pads = request.Pads,
            LockCurves = locks[..2],
            HardConstraints = request.HardConstraints,
            ModelTolerance = request.ModelTolerance,
            TerrainDetailSize = request.TerrainDetailSize
        };
        Assert.True(PadGrader.Grade(withoutContour).Result!.CutVolume > whole.CutVolume + 500);
    }

