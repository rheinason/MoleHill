/// <summary>
/// A curb inserted by Add Geometry across a band of contour slivers (Verandi Lendi, 2026-10-06). Cut from the
/// live terrain around the one curb segment that folded it: the segment crosses a 0.1 m wide, 3.3 m long
/// sliver whose edges it meets a few millimetres apart, and a split point lands 2.95 mm off one edge — inside
/// the 5 mm tolerance. Triangulated face by face, one neighbour took that point as on the shared edge and the
/// other as inside its face, so the two overlapped and an edge carried three faces. Lawson flips then read a
/// face index of -1 and the build failed with an IndexOutOfRangeException.
/// </summary>
public sealed class ContourSliverCurbInsertionCaseTests
{
    private const double Tolerance = 0.005;

    [Fact]
    public void TryInsert_CurbAcrossContourSlivers_NeverReturnsAFoldedMesh()
    {
        bool inserted = MeshConstraintTopologyInserter.TryInsert(
            new IndexedTriMesh(Vertices, Vertices.Length / 3, Faces, Faces.Length / 3),
            [Curb()],
            Tolerance,
            out IndexedTriMesh insertedMesh,
            out string? error);
        double[] vertices = insertedMesh.Vertices;
        int vertexCount = insertedMesh.VertexCount;
        int[] faces = insertedMesh.Faces;
        int faceCount = insertedMesh.FaceCount;

        Assert.True(inserted, error);
        Assert.True(vertexCount > Vertices.Length / 3, "The curb must split the faces it crosses.");
        AssertTilesInput(vertices, faces, faceCount);
    }

    [Fact]
    public void TerrainDetailInserter_CurbAcrossContourSlivers_InsertsOrDeclinesWithoutThrowing()
    {
        bool inserted = TerrainDetailInserter.TryInsert(
            Vertices, Vertices.Length / 3, Faces, Faces.Length / 3, [], [Curb()], [], [],
            Tolerance, 0.0125, 70.0, out TerrainDetailInserter.Result? result, out string? error);

        if (inserted)
            AssertTilesInput(result!.Vertices, result.Faces, result.FaceCount);
        else
            Assert.False(string.IsNullOrWhiteSpace(error));
    }

    /// <summary>
    /// The same terrain after Triangulate's input repair (8 m around the spot): a curb crosses an edge 4.9 mm
    /// from the far corner of the sliver on the other side. That sliver treated the split as "at my corner"
    /// and kept the edge whole while its neighbour cut it - a zero-area slit in the terrain.
    /// </summary>
    [Fact]
    public void TryInsert_SplitNearSliverFarCorner_CutsBothSidesOfTheEdge()
    {
        var before = MeshTopologyValidator.AnalyzeBoundaryGraph(FarCornerFaces, FarCornerFaces.Length / 3);
        ConstraintPolyline curb = new([-1.4930085585699615, -0.7861726487189813, 7.399371621116108, 1.9195150946215733, 1.3006149102836844, 7.399371621116108], 2, IsClosed: false, PreserveInputElevation: true);
        bool inserted = MeshConstraintTopologyInserter.TryInsert(
            new IndexedTriMesh(FarCornerVertices, FarCornerVertices.Length / 3, FarCornerFaces, FarCornerFaces.Length / 3),
            [curb],
            Tolerance,
            out IndexedTriMesh insertedMesh2,
            out string? error);
        int vertexCount = insertedMesh2.VertexCount;
        int[] faces = insertedMesh2.Faces;
        int faceCount = insertedMesh2.FaceCount;

        Assert.True(inserted, error);
        Assert.True(vertexCount > FarCornerVertices.Length / 3);
        var after = MeshTopologyValidator.AnalyzeBoundaryGraph(faces, faceCount);
        Assert.Equal(0, after.NonManifoldEdgeCount);
        Assert.Equal(before.BoundaryComponentCount, after.BoundaryComponentCount);

        // Face by face, not by the one-piece retry: that re-triangulates every face sharing a vertex with the
        // curb's, so it keeps fewer input faces as they were. Before the fix this case only passed that way.
        MeshConstraintTopologyInserter.TryInsertByLocalTriangulation(
            FarCornerVertices, FarCornerVertices.Length / 3, FarCornerFaces, FarCornerFaces.Length / 3, [curb], Tolerance,
            out _, out _, out int[] onePieceFaces, out int onePieceFaceCount, out _);
        Assert.True(KeptInputFaces(faces, faceCount) > KeptInputFaces(onePieceFaces, onePieceFaceCount));
    }

    private static int KeptInputFaces(int[] faces, int faceCount)
    {
        var output = new HashSet<(int, int, int)>();
        for (int f = 0; f < faceCount; f++)
            output.Add(Canonical(faces[f * 3], faces[(f * 3) + 1], faces[(f * 3) + 2]));

        int kept = 0;
        for (int f = 0; f < FarCornerFaces.Length / 3; f++)
        {
            if (output.Contains(Canonical(FarCornerFaces[f * 3], FarCornerFaces[(f * 3) + 1], FarCornerFaces[(f * 3) + 2])))
                kept++;
        }

        return kept;
    }

    private static (int, int, int) Canonical(int a, int b, int c)
    {
        int[] sorted = [a, b, c];
        Array.Sort(sorted);
        return (sorted[0], sorted[1], sorted[2]);
    }

