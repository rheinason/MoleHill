    private static void AssertTilesInput(double[] vertices, int[] faces, int faceCount)
    {
        var uses = IndexedMeshTools.CreateEdgeKeyMap<int>(faceCount * 3);
        double area = 0.0;
        for (int f = 0; f < faceCount; f++)
        {
            for (int k = 0; k < 3; k++)
            {
                long key = IndexedMeshTools.GetEdgeKey(faces[(f * 3) + k], faces[(f * 3) + ((k + 1) % 3)]);
                uses[key] = uses.GetValueOrDefault(key) + 1;
            }

            area += PlanArea(vertices, faces[f * 3], faces[(f * 3) + 1], faces[(f * 3) + 2]);
        }

        double inputArea = 0.0;
        for (int f = 0; f < Faces.Length / 3; f++)
            inputArea += PlanArea(Vertices, Faces[f * 3], Faces[(f * 3) + 1], Faces[(f * 3) + 2]);

        Assert.DoesNotContain(uses.Values, count => count > 2);
        Assert.Equal(inputArea, area, 6);
    }

