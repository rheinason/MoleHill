        Assert.True(string.IsNullOrWhiteSpace(errorMessage) || !errorMessage.Contains("failed", StringComparison.OrdinalIgnoreCase), errorMessage);

        string? dumpPath = Environment.GetEnvironmentVariable("MOLEHILL_DUMP_OBJ");
        if (!string.IsNullOrEmpty(dumpPath))
        {
            var sb = new System.Text.StringBuilder();
            for (int i = 0; i < result!.VertexCount; i++)
                sb.AppendLine(FormattableString.Invariant($"v {result.Vertices[i * 3]} {result.Vertices[i * 3 + 1]} {result.Vertices[i * 3 + 2]}"));
            for (int f = 0; f < result.FaceCount; f++)
                sb.AppendLine(FormattableString.Invariant($"f {result.Faces[f * 3] + 1} {result.Faces[f * 3 + 1] + 1} {result.Faces[f * 3 + 2] + 1}"));
            File.WriteAllText(dumpPath, sb.ToString());
        }

        string diagnostics = string.Join(Environment.NewLine, result!.Diagnostics);

        // The graded mesh must stay watertight and manifold — the old fallback shipped 2 non-manifold
        // edges, open chains, and boundary components 1 -> 3 on this scene.
        PadInvariantAssert.AssertWatertightManifold(result, diagnostics);

        MeshTopologyValidator.BoundaryGraphAnalysis input =
            MeshTopologyValidator.AnalyzeBoundaryGraph(faces, faceCount);
        MeshTopologyValidator.BoundaryGraphAnalysis output =
            MeshTopologyValidator.AnalyzeBoundaryGraph(result.Faces, result.FaceCount);
        Assert.True(
            output.BoundaryComponentCount <= input.BoundaryComponentCount,
            $"Grading opened new boundary loops: {input.BoundaryComponentCount} -> {output.BoundaryComponentCount}." +
            Environment.NewLine + diagnostics);

        // No new near-vertical spikes AWAY from the protected-pad lock curves: retaining walls
        // against a hard constraint are intended (walls are never buried), so faces hugging a
        // hard-constraint segment are exempt. Everything else may not get steeper than what the
        // input terrain already contained plus the 33 deg batter (generous margin for conformed
        // facets).
        double inputMaxSlopeDeg = MaxFaceSlopeDegrees(vertices, faces, faceCount, hardConstraints, wallExclusionDistance: 3.0);
        double allowedDeg = Math.Min(88.0, Math.Max(inputMaxSlopeDeg, 33.0) + 10.0);
        double outputMaxSlopeDeg = MaxFaceSlopeDegrees(result.Vertices, result.Faces, result.FaceCount, hardConstraints, wallExclusionDistance: 3.0);
        Assert.True(
            outputMaxSlopeDeg <= allowedDeg,
            $"Graded mesh contains spike faces away from hard-constraint walls: max slope {outputMaxSlopeDeg:F1} deg " +
            $"exceeds allowed {allowedDeg:F1} deg (input terrain max {inputMaxSlopeDeg:F1} deg) " +
            $"at ({WorstFaceCentroid.X:F2}, {WorstFaceCentroid.Y:F2})." +
            Environment.NewLine + DescribeSteepFaces(result.Vertices, result.Faces, result.FaceCount, hardConstraints, allowedDeg) +
            Environment.NewLine + diagnostics);
    }

    /// <summary>
    /// Steepest face slope (angle from horizontal) across the mesh, ignoring degenerate faces and
    /// faces whose centroid lies within <paramref name="wallExclusionDistance"/> of a hard-constraint
    /// segment (legitimate retaining walls form there).
    /// </summary>
    private static double MaxFaceSlopeDegrees(
        double[] vertices,
        int[] faces,
        int faceCount,
        ConstraintPolyline[] hardConstraints,
        double wallExclusionDistance)
    {
        double maxTanSq = 0.0;
        for (int f = 0; f < faceCount; f++)
        {
            int a = faces[f * 3];
            int b = faces[f * 3 + 1];
            int c = faces[f * 3 + 2];
            double ux = vertices[b * 3] - vertices[a * 3];
            double uy = vertices[b * 3 + 1] - vertices[a * 3 + 1];
            double uz = vertices[b * 3 + 2] - vertices[a * 3 + 2];
            double vx = vertices[c * 3] - vertices[a * 3];
            double vy = vertices[c * 3 + 1] - vertices[a * 3 + 1];
            double vz = vertices[c * 3 + 2] - vertices[a * 3 + 2];
            double nx = (uy * vz) - (uz * vy);
            double ny = (uz * vx) - (ux * vz);
            double nz = (ux * vy) - (uy * vx);
            double horizontalSq = (nx * nx) + (ny * ny);
            double areaSq = horizontalSq + (nz * nz);
            if (areaSq < 1e-16)
                continue;

            double tanSq = horizontalSq / (nz * nz + 1e-30);
            if (tanSq <= maxTanSq)
                continue;

            // A face with ANY vertex on/near a hard constraint is a retaining-wall transition face
            // (they can be large, so a centroid test is not enough).
            if (DistanceToConstraints(vertices[a * 3], vertices[a * 3 + 1], hardConstraints) <= wallExclusionDistance ||
                DistanceToConstraints(vertices[b * 3], vertices[b * 3 + 1], hardConstraints) <= wallExclusionDistance ||
                DistanceToConstraints(vertices[c * 3], vertices[c * 3 + 1], hardConstraints) <= wallExclusionDistance)
            {
                continue;
            }

            maxTanSq = tanSq;
            WorstFaceCentroid = (
                (vertices[a * 3] + vertices[b * 3] + vertices[c * 3]) / 3.0,
                (vertices[a * 3 + 1] + vertices[b * 3 + 1] + vertices[c * 3 + 1]) / 3.0);
        }

        return Math.Atan(Math.Sqrt(maxTanSq)) * (180.0 / Math.PI);
    }

    private static (double X, double Y) WorstFaceCentroid;

    /// <summary>Debug detail for spike failures: every face steeper than the allowance, with geometry.</summary>
    private static string DescribeSteepFaces(
        double[] vertices, int[] faces, int faceCount,
        ConstraintPolyline[] hardConstraints, double allowedDeg)
    {
        var lines = new List<string>();
        double allowedTanSq = Math.Tan(allowedDeg * Math.PI / 180.0);
        allowedTanSq *= allowedTanSq;
        for (int f = 0; f < faceCount && lines.Count < 25; f++)
        {
            int a = faces[f * 3];
            int b = faces[f * 3 + 1];
            int c = faces[f * 3 + 2];
            double ux = vertices[b * 3] - vertices[a * 3];
            double uy = vertices[b * 3 + 1] - vertices[a * 3 + 1];
            double uz = vertices[b * 3 + 2] - vertices[a * 3 + 2];
            double vx = vertices[c * 3] - vertices[a * 3];
            double vy = vertices[c * 3 + 1] - vertices[a * 3 + 1];
            double vz = vertices[c * 3 + 2] - vertices[a * 3 + 2];
            double nx = (uy * vz) - (uz * vy);
            double ny = (uz * vx) - (ux * vz);
            double nz = (ux * vy) - (uy * vx);
            double horizontalSq = (nx * nx) + (ny * ny);
            if (horizontalSq + (nz * nz) < 1e-16 || horizontalSq <= allowedTanSq * (nz * nz + 1e-30))
                continue;

            double cx = (vertices[a * 3] + vertices[b * 3] + vertices[c * 3]) / 3.0;
            double cy = (vertices[a * 3 + 1] + vertices[b * 3 + 1] + vertices[c * 3 + 1]) / 3.0;
            double slope = Math.Atan(Math.Sqrt(horizontalSq / (nz * nz + 1e-30))) * (180.0 / Math.PI);
            double distToWall = DistanceToConstraints(cx, cy, hardConstraints);
            double e0 = Math.Sqrt((ux * ux) + (uy * uy));
            double e1 = Math.Sqrt((vx * vx) + (vy * vy));
            double wx = vertices[c * 3] - vertices[b * 3];
            double wy = vertices[c * 3 + 1] - vertices[b * 3 + 1];
            double e2 = Math.Sqrt((wx * wx) + (wy * wy));
            lines.Add(
                $"  face {f}: slope={slope:F1} deg centroid=({cx:F2},{cy:F2}) wallDist={distToWall:F2} " +
                $"xyEdges=({e0:F3},{e1:F3},{e2:F3}) z=({vertices[a * 3 + 2]:F2},{vertices[b * 3 + 2]:F2},{vertices[c * 3 + 2]:F2})");
        }

        return $"Steep faces ({lines.Count} shown):" + Environment.NewLine + string.Join(Environment.NewLine, lines);
    }

    private static double DistanceToConstraints(double x, double y, ConstraintPolyline[] hardConstraints)
    {
        double best = double.MaxValue;
        foreach (ConstraintPolyline constraint in hardConstraints)
        {
            int n = constraint.PointCount;
            int segmentCount = constraint.IsClosed ? n : n - 1;
            for (int i = 0; i < segmentCount; i++)
            {
                int j = (i + 1) % n;
                double ax = constraint.Points[i * 3];
                double ay = constraint.Points[i * 3 + 1];
                double bx = constraint.Points[j * 3];
                double by = constraint.Points[j * 3 + 1];
                double dx = bx - ax;
                double dy = by - ay;
                double lenSq = (dx * dx) + (dy * dy);
                double t = lenSq < 1e-16 ? 0.0 : Math.Clamp((((x - ax) * dx) + ((y - ay) * dy)) / lenSq, 0.0, 1.0);
                double px = ax + (t * dx) - x;
                double py = ay + (t * dy) - y;
                double d = Math.Sqrt((px * px) + (py * py));
                if (d < best)
                    best = d;
            }
        }

        return best;
    }
