/// <summary>
/// Wall rails inserted into a terrain that fell back to plain Delaunay, so its faces include long slivers.
/// Both fixtures are cut from a real case (24 breakline-mode walls, none of them inserted) that Triangulate
/// could only build without its breaklines.
///
/// <para>The sliver fan: a rail crosses one edge 9 mm from a vertex where the next edge round passes 0.9 mm
/// away. Face-by-face insertion recorded the crossing on only one of the sliver's two edges, then merged the
/// two points into one vertex lying on the other edge, keeping a zero-area triangle on an edge its neighbour
/// split. That edge was used once on one side and three times on the other, and the insertion was refused
/// as breaking the terrain border.</para>
///
/// <para>The hull fan: dozens of 48 m slivers radiating from one vertex. Face-by-face insertion cannot place
/// crossings millimetres apart consistently, and the local re-triangulation that exists for exactly that
/// case kept convex-hull filler triangles, micrometres wide, that point location placed inside the patch.
/// Every rail of the case failed its area check.</para>
/// </summary>
public class WallRailSliverInsertionTests
{
    private const double Tolerance = 0.005;

    [Fact]
    public void TryInsert_RailCrossingNextToSliver_KeepsEveryEdgeShared()
    {
        int vertexCount = SliverFanVertices.Length / 3, faceCount = SliverFanFaces.Length / 3;
        var before = MeshTopologyValidator.AnalyzeBoundaryGraph(SliverFanFaces, faceCount);

        bool inserted = MeshConstraintTopologyInserter.TryInsert(
            new IndexedTriMesh(SliverFanVertices, vertexCount, SliverFanFaces, faceCount),
            new[] { SliverFanRail },
            Tolerance,
            out IndexedTriMesh insertedMesh,
            out string? error);
        int[] faces = insertedMesh.Faces;
        int outputFaceCount = insertedMesh.FaceCount;

        Assert.True(inserted, error);
        var after = MeshTopologyValidator.AnalyzeBoundaryGraph(faces, outputFaceCount);
        Assert.Equal(0, after.NonManifoldEdgeCount);
        Assert.Equal(before.BoundaryComponentCount, after.BoundaryComponentCount);
        Assert.Equal(before.HasOpenBoundaryChains, after.HasOpenBoundaryChains);
    }

    [Fact]
    public void TryInsertByLocalTriangulation_RailAcrossHullSliverFan_Succeeds()
    {
        int vertexCount = HullSliverFanVertices.Length / 3, faceCount = HullSliverFanFaces.Length / 3;
        var before = MeshTopologyValidator.AnalyzeBoundaryGraph(HullSliverFanFaces, faceCount);

        bool inserted = MeshConstraintTopologyInserter.TryInsertByLocalTriangulation(
            HullSliverFanVertices, vertexCount, HullSliverFanFaces, faceCount, new[] { HullSliverFanRail }, Tolerance,
            out _, out _, out int[] faces, out int outputFaceCount, out string? error);

        Assert.True(inserted, error);
        var after = MeshTopologyValidator.AnalyzeBoundaryGraph(faces, outputFaceCount);
        Assert.Equal(0, after.NonManifoldEdgeCount);
        Assert.Equal(before.BoundaryComponentCount, after.BoundaryComponentCount);
        Assert.True(outputFaceCount > faceCount);
    }

