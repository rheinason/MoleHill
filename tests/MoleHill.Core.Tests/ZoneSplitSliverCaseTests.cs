/// <summary>
/// Zone splitting on the Verandi Lendi terrain (2026-10-06), cut 6 m around two spots where 9 of 14 zone
/// meshes came out non-manifold. The splitter re-triangulated each face on its own and resolved every point
/// to the nearest vertex within tolerance, so a split of one edge merged into a sliver's far corner or into a
/// split of the next edge over, and neighbouring faces overlapped. It also fused two corners 6.7 mm apart
/// (under the 12.5 mm tolerance), dropping the triangle between them. Splits now resolve per edge.
/// </summary>
public sealed class ZoneSplitSliverCaseTests
{
    [Theory]
    [InlineData(0)]
    [InlineData(1)]
    public void SplitPreservingTopology_SliverTerrain_TilesTheTerrainExactly(int fixture)
    {
        (double[] vertices, int[] faces, double[][] zones) = fixture == 0 ? (Vertices0, Faces0, Zones0) : (Vertices1, Faces1, Zones1);
        var areas = zones.Select(xy => new MeshAreaSplitter.AreaBoundary(xy, xy.Length / 2)).ToArray();

        MeshAreaSplitter.SplitResult? result = MeshAreaSplitter.SplitPreservingTopology(
            vertices, vertices.Length / 3, faces, faces.Length / 3, areas, 0.0125, out string? error);

        Assert.NotNull(result);
        var uses = IndexedMeshTools.CreateEdgeKeyMap<int>(result!.FaceCount * 3);
        for (int t = 0; t < result.FaceCount; t++)
        {
            for (int k = 0; k < 3; k++)
            {
                long key = IndexedMeshTools.GetEdgeKey(result.Faces[(t * 3) + k], result.Faces[(t * 3) + ((k + 1) % 3)]);
                uses[key] = uses.GetValueOrDefault(key) + 1;
            }
        }

        Assert.DoesNotContain(uses.Values, count => count > 2);
        Assert.Equal(PlanArea(vertices, faces, faces.Length / 3), PlanArea(result.Vertices, result.Faces, result.FaceCount), 6);
    }

    private static double PlanArea(double[] v, int[] f, int faceCount)
    {
        double area = 0.0;
        for (int t = 0; t < faceCount; t++)
        {
            int a = f[t * 3], b = f[(t * 3) + 1], c = f[(t * 3) + 2];
            area += Math.Abs(((v[b * 3] - v[a * 3]) * (v[(c * 3) + 1] - v[(a * 3) + 1])) - ((v[(b * 3) + 1] - v[(a * 3) + 1]) * (v[c * 3] - v[a * 3]))) * 0.5;
        }

        return area;
    }

